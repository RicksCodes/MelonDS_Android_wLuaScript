# --- Round utility buttons with line icons (128) ---
def utility(name, icon_paths, disabled=False):
    alpha = DISABLED_ALPHA if disabled else 1.0
    paths = [shape(circle(64, 64, 56), fill=FILL, stroke=STROKE, width=3.5, alpha=alpha)]
    paths += [shape(d, stroke=ICON, width=5, alpha=alpha) for d in icon_paths]
    if disabled:
        paths.append(shape("M40,40 L88,88", stroke=ICON, width=5, alpha=0.9))
    vector(name, 40, 128, paths)


def arc_arrow(cx, cy, radius, start_deg, sweep_deg, head=11):
    """Clockwise arc (screen coordinates) with an arrow head at its end."""
    s, e = math.radians(start_deg), math.radians(start_deg + sweep_deg)
    x0, y0 = cx + radius * math.cos(s), cy + radius * math.sin(s)
    x1, y1 = cx + radius * math.cos(e), cy + radius * math.sin(e)
    large = 1 if sweep_deg > 180 else 0
    d = f"M{n(x0)},{n(y0)} A{n(radius)},{n(radius)} 0 {large},1 {n(x1)},{n(y1)}"
    tx, ty = -math.sin(e), math.cos(e)          # direction of travel at the end
    wings = []
    for angle in (150, -150):
        a = math.radians(angle)
        wx = tx * math.cos(a) - ty * math.sin(a)
        wy = tx * math.sin(a) + ty * math.cos(a)
        wings.append((x1 + wx * head, y1 + wy * head))
    d2 = f"M{n(wings[0][0])},{n(wings[0][1])} L{n(x1)},{n(y1)} L{n(wings[1][0])},{n(wings[1][1])}"
    return [d, d2]


