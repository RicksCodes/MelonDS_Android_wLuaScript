"""
Generates thin, outline-style vector drawables for melonDS Android's on-screen controls.
Letters come from Roboto (Apache 2.0, bundled with Android Studio's layoutlib).
Usage: python gen_controls.py <res/drawable dir> <fonts dir>
"""
import math
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

OUT = Path(sys.argv[1])
FONTS = Path(sys.argv[2])

FILL = "#1AFFFFFF"        # very light glassy fill
STROKE = "#D9FFFFFF"      # thin outline
LABEL = "#F2FFFFFF"
ICON = "#F2FFFFFF"
ACCENT = "#99FFFFFF"      # d-pad arrows
DISABLED_ALPHA = 0.45
# Soft dark halo under outlines, labels and icons, so that the controls stay visible over white screens. Two layers
# (wide and faint, narrow and darker) shifted slightly down. Sizes are for a 128 viewport and scale with it.
SHADOW_SOFT = ("#1C000000", 7.0)
SHADOW_CORE = ("#30000000", 2.5)
SHADOW_OFFSET_Y = 1.5


class Font:
    def __init__(self, path):
        self.font = TTFont(path)
        self.glyphs = self.font.getGlyphSet()
        self.cmap = self.font.getBestCmap()
        self.cap = self.font["OS/2"].sCapHeight

    def text_path(self, text, cx, cy, cap_height, tracking=0.0):
        """SVG path of `text` with its cap height centred on (cx, cy). tracking is in em fractions."""
        scale = cap_height / self.cap
        upm = self.font["head"].unitsPerEm
        names = [self.cmap[ord(c)] for c in text]
        advances = [self.font["hmtx"][n][0] for n in names]
        total = sum(advances) + tracking * upm * (len(text) - 1)
        x = cx - total * scale / 2
        baseline = cy + cap_height / 2
        out = []
        for name, adv in zip(names, advances):
            pen = SVGPathPen(self.glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
            self.glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, x, baseline)))
            out.append(pen.getCommands())
            x += (adv + tracking * upm) * scale
        return " ".join(out)


regular = Font(FONTS / "Roboto-Regular.ttf")
medium = Font(FONTS / "Roboto-Medium.ttf")


def n(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def circle(cx, cy, r):
    return f"M{n(cx - r)},{n(cy)} a{n(r)},{n(r)} 0 1,0 {n(2 * r)},0 a{n(r)},{n(r)} 0 1,0 {n(-2 * r)},0 Z"


def rrect(x1, y1, x2, y2, r):
    return (f"M{n(x1 + r)},{n(y1)} L{n(x2 - r)},{n(y1)} A{n(r)},{n(r)} 0 0,1 {n(x2)},{n(y1 + r)} "
            f"L{n(x2)},{n(y2 - r)} A{n(r)},{n(r)} 0 0,1 {n(x2 - r)},{n(y2)} L{n(x1 + r)},{n(y2)} "
            f"A{n(r)},{n(r)} 0 0,1 {n(x1)},{n(y2 - r)} L{n(x1)},{n(y1 + r)} A{n(r)},{n(r)} 0 0,1 {n(x1 + r)},{n(y1)} Z")


def with_alpha(color, factor):
    a = int(color[1:3], 16)
    return f"#{int(a * factor):02X}{color[3:]}"


def path_xml(d, fill=None, stroke=None, width=0.0, indent="    "):
    attrs = [f'android:pathData="{d}"']
    if fill:
        attrs.append(f'android:fillColor="{fill}"')
    if stroke:
        attrs += [f'android:strokeColor="{stroke}"', f'android:strokeWidth="{n(width)}"',
                  'android:strokeLineCap="round"', 'android:strokeLineJoin="round"']
    return indent + "<path " + ("\n" + indent + "    ").join(attrs) + " />"


def shape(d, fill=None, stroke=None, width=0.0, alpha=1.0):
    return dict(d=d, fill=with_alpha(fill, alpha) if fill else None, stroke=with_alpha(stroke, alpha) if stroke else None,
                width=width, alpha=alpha)


def shadow(paths, viewport):
    """Halo under each path. The glassy fill of the button bodies is left out: only their outline casts a shadow."""
    k = viewport / 128
    out = [f'    <group android:translateY="{n(SHADOW_OFFSET_Y * k)}">']
    for color, extra in (SHADOW_SOFT, SHADOW_CORE):
        for p in paths:
            c = with_alpha(color, p["alpha"])
            body = p["fill"] is not None and p["fill"].upper().endswith("FFFFFF") and p["fill"][1:3] == FILL[1:3] and p["stroke"]
            if p["stroke"]:
                out.append(path_xml(p["d"], stroke=c, width=p["width"] + extra * k, indent="        "))
            if p["fill"] and not body:
                out.append(path_xml(p["d"], fill=c, stroke=c, width=extra * k, indent="        "))
    out.append("    </group>")
    return out


def vector(name, size_dp, viewport, paths):
    xml = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by gen_controls.py: thin outline controls with a soft shadow. Labels: Roboto (Apache 2.0). -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           f'    android:width="{size_dp}dp"', f'    android:height="{size_dp}dp"',
           f'    android:viewportWidth="{viewport}"', f'    android:viewportHeight="{viewport}">']
    xml += shadow(paths, viewport)
    xml += [path_xml(p["d"], fill=p["fill"], stroke=p["stroke"], width=p["width"]) for p in paths]
    xml.append("</vector>")
    (OUT / f"{name}.xml").write_text("\n".join(xml) + "\n", encoding="utf-8")


